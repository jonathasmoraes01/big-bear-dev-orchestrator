"""Builds hooks/src/ui/avatar-data.ts from assets/avatar/*.png.

The hooks module runs with no filesystem, so the avatars ship as data:
- an SVG of square pixels (the desktop app draws `Svg`, not `Image`);
- terminal cells for `Raster`: the upper half block, its foreground the top
  pixel and its background the bottom one, so one cell holds two pixels.

Run: python tools/build-avatars.py
"""

import base64
import json
import struct
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
STATES = {"idle": "idle.png", "research": "research.png", "work": "work.png"}
SVG_PX = 40  # pixels across the SVG
CELL_SIZES = {"lg": 24, "sm": 16, "xs": 12}  # columns of the terminal avatar (rows = columns / 2)
DEFAULT = 0x01000000
HALF = 0x2580  # upper half block


def load(name: str, size: int) -> Image.Image:
    im = Image.open(ROOT / "assets" / "avatar" / name).convert("RGBA")
    box = im.getbbox() or (0, 0, im.width, im.height)
    # Square crop around the drawn part, so the bear fills the avatar.
    left, top, right, bottom = box
    side = max(right - left, bottom - top)
    cx, cy = (left + right) // 2, (top + bottom) // 2
    im = im.crop((cx - side // 2, cy - side // 2, cx - side // 2 + side, cy - side // 2 + side))
    return im.resize((size, size), Image.Resampling.BOX)


def svg(im: Image.Image) -> str:
    w, h = im.size
    rects = []
    px = im.load()
    for y in range(h):
        x = 0
        while x < w:
            r, g, b, a = px[x, y]
            if a < 110:
                x += 1
                continue
            color = f"#{r:02x}{g:02x}{b:02x}"
            run = 1
            while x + run < w:
                r2, g2, b2, a2 = px[x + run, y]
                if a2 < 110 or f"#{r2:02x}{g2:02x}{b2:02x}" != color:
                    break
                run += 1
            rects.append(f'<rect x="{x}" y="{y}" width="{run}" height="1" fill="{color}"/>')
            x += run
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" '
        f'shape-rendering="crispEdges">{"".join(rects)}</svg>'
    )


def quantize(im: Image.Image) -> Image.Image:
    # Fewer distinct colors make longer runs and a smaller SVG.
    rgb = im.convert("RGB").quantize(colors=48, method=Image.Quantize.MEDIANCUT).convert("RGB")
    out = Image.new("RGBA", im.size)
    alpha = im.getchannel("A")
    out.paste(rgb)
    out.putalpha(alpha)
    return out


def cells(im: Image.Image) -> str:
    w, h = im.size
    px = im.load()
    words = []
    for row in range(h // 2):
        for x in range(w):
            top = px[x, row * 2]
            bottom = px[x, row * 2 + 1]
            fg = (top[0] << 16 | top[1] << 8 | top[2]) if top[3] >= 110 else DEFAULT
            bg = (bottom[0] << 16 | bottom[1] << 8 | bottom[2]) if bottom[3] >= 110 else DEFAULT
            if fg == DEFAULT and bg == DEFAULT:
                words += [0x20, DEFAULT, DEFAULT]
            elif fg == DEFAULT:
                # Only the bottom pixel: a lower half block in its color.
                words += [0x2584, bg, DEFAULT]
            else:
                words += [HALF, fg, bg]
    return base64.b64encode(struct.pack(f"<{len(words)}I", *words)).decode()


def main() -> None:
    data = {}
    for state, name in STATES.items():
        entry = {"svg": svg(quantize(load(name, SVG_PX)))}
        for label, columns in CELL_SIZES.items():
            entry[label] = {"columns": columns, "rows": columns // 2, "cells": cells(load(name, columns))}
        data[state] = entry
    out = ROOT / "hooks" / "src" / "ui" / "avatar-data.ts"
    body = json.dumps(data, separators=(",", ":"))
    out.write_text(
        "// Generated by tools/build-avatars.py from assets/avatar/*.png. Do not edit.\n"
        "export type AvatarRaster = { columns: number; rows: number; cells: string }\n"
        "export type AvatarFrames = { svg: string; lg: AvatarRaster; sm: AvatarRaster; xs: AvatarRaster }\n"
        f"export const AVATARS: Record<'idle' | 'research' | 'work', AvatarFrames> = {body}\n",
        encoding="utf-8",
    )
    for state, entry in data.items():
        print(state, "svg chars:", len(entry["svg"]))
    print("wrote", out, out.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
